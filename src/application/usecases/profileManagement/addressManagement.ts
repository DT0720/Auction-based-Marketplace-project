import { Address } from "@/domain/entities/Address"; // Adjust import path based on your project structure
import { IAddressRepository } from "@/application/repositories/IAddressRepository"; // Adjust import path based on your project structure
import { AddressRepository } from "@/infrastructure/repositories/AddressRepository";

// Function to add a new address
export async function addAddress(user_id: number, flat_no: string, house_no: string, house_name: string, road_no: string, sector: number, area: string, city: string): Promise<Address | null> {
    const addressRepository : IAddressRepository = new AddressRepository();
    const newAddress = new Address(0, user_id, flat_no, house_no, house_name, road_no, sector, area, city); // ID will be auto-generated by the database
    return await addressRepository.create(newAddress);
}

// Function to update an existing address
export async function updateAddress(id: number, flat_no?: string, house_no?: string, house_name?: string, road_no?: string, sector?: number, area?: string, city?: string): Promise<boolean> {
    const addressRepository : IAddressRepository = new AddressRepository();
    const existingAddress = await addressRepository.findById(id);
    if (!existingAddress) {
        throw new Error('Address not found');
    }

    const updatedAddress = new Address(
        id,
        existingAddress.user_id,
        flat_no ?? existingAddress.flat_no,
        house_no ?? existingAddress.house_no,
        house_name ?? existingAddress.house_name,
        road_no ?? existingAddress.road_no,
        sector ?? existingAddress.sector,
        area ?? existingAddress.area,
        city ?? existingAddress.city
    );

    return await addressRepository.update(updatedAddress);
}

// Function to delete an address
export async function deleteAddress(id: number): Promise<boolean> {
    const addressRepository : IAddressRepository = new AddressRepository();
    const existingAddress = await addressRepository.findById(id);
    if (!existingAddress) {
        throw new Error('Address not found');
    }
    return await addressRepository.delete(id);
}

// Function to retrieve an address by ID
export async function getAddressById(id: number): Promise<Address | null> {
    const addressRepository : IAddressRepository = new AddressRepository();
    return await addressRepository.findById(id);
}

// Function to retrieve all addresses for a user
export async function getAddressesByUserId(user_id: number): Promise<Address[]> {
    const addressRepository : IAddressRepository = new AddressRepository();
    return await addressRepository.findByUserId(user_id);
}