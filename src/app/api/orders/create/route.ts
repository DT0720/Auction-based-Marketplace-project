import { NextResponse } from 'next/server';
import { OrderRepository } from '@/infrastructure/repositories/OrderRepository';
import { Order } from '@/domain/entities/Order';
import { OrderDetails } from '@/domain/entities/OrderDetails';
import { SellerInventoryRepository } from '@/infrastructure/repositories/SellerInventoryRepository';

const orderRepository = new OrderRepository();
const sellerInventoryRepository = new SellerInventoryRepository();

export async function POST(req: Request) {
  try {
    const body = await req.json();

    // Validate the request body
    if (!body || !body.buyer_id || !body.status || !body.total_amount || !body.orderDetails) {
      return new Response('Missing required fields', { status: 400 });
    }

    // Extract product IDs
    const productIds = body.orderDetails.map((detail: any) => detail.product_id);

    // Fetch seller IDs for the products
    const sellersWithProducts = await sellerInventoryRepository.getSellerIdsByProductIds(productIds);

    // Match seller IDs with their products in order details
    const orderDetails = body.orderDetails.map((detail: any) => {
      const seller = sellersWithProducts.find((item) => item.product_id === detail.product_id);
      if (!seller) {
        throw new Error(`Seller not found for product ID: ${detail.product_id}`);
      }

      return new OrderDetails(0, 0, detail.product_id, detail.quantity, seller.seller_id);
    });

    // Create the order
    const order = new Order(
      0, // ID will be generated by the DB
      body.buyer_id,
      body.offer_id || null,
      body.status,
      body.total_amount
    );

    // Use the repository method
    // const { order: createdOrder, orderDetails: createdOrderDetails } = await orderRepository.createOrderWithDetails(order, orderDetails);

    const { order: createdOrder, orderDetails: createdOrderDetails } = await orderRepository.createOrderWithDetailsAndUpdateInventory(order, orderDetails, body.user_id);
    
    return NextResponse.json(
      {
        message: 'Order created successfully',
        data: {
          order: createdOrder,
          orderDetails: createdOrderDetails,
        },
      },
      { status: 201 }
    );
  } catch (error: any) {
    console.error('Error in creating order:', error);
    return NextResponse.json(
      { message: error.message || 'Failed to create order' },
      { status: 400 }
    );
  }
}
