// src/app/api/orders/create/route.ts
import { NextResponse } from 'next/server';
import { OrderRepository } from '@/infrastructure/repositories/OrderRepository';
import { OrderDetailsRepository } from '@/infrastructure/repositories/OrderDetailsRepository';
import { Order } from '@/domain/entities/Order';
import { OrderDetails } from '@/domain/entities/OrderDetails';

const orderRepository = new OrderRepository();
const orderDetailsRepository = new OrderDetailsRepository();

export async function POST(req: Request) {
  try {
    const body = await req.json();

    // Validate the received body
    if (!body || !body.buyer_id || !body.status || !body.total_amount || !body.orderDetails) {
      return new Response('Missing required fields', { status: 400 });
    }

    // Create the order object
    const order = new Order(
      0, // ID will be generated by the DB
      body.buyer_id,
      body.offer_id || null,
      body.status,
      body.total_amount
      
    );

    // Create the order using the orderRepository
    const createdOrder = await orderRepository.create(order);

    // Prepare and create order details
    const orderDetailsPromises = body.orderDetails.map((detail: any) => {
      const orderDetail = new OrderDetails(
        0, // ID will be generated by the DB
        createdOrder.id, // Associated order ID
        detail.product_id,
        detail.quantity,
        detail.seller_id
      );
      return orderDetailsRepository.create(orderDetail);
    });

    // Wait for all order details to be created
    const createdOrderDetails = await Promise.all(orderDetailsPromises);

    // Return the response with both the created order and its order details
    return NextResponse.json(
      {
        message: 'Order created successfully',
        data: {
          order: createdOrder,
          orderDetails: createdOrderDetails,
        }
      },
      { status: 201 }
    );
  } catch (error: any) {
    return NextResponse.json(
      { message: error.message || 'Failed to create order' },
      { status: 400 }
    );
  }
}
